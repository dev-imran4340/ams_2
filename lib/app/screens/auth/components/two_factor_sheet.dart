import 'package:flutter/material.dart';
import 'package:flutter/services.dart';
import 'package:flutter_screenutil/flutter_screenutil.dart';
import 'package:get/get.dart';

import '../../../core/utils/app_colors.dart';
import '../../../core/utils/app_spaces.dart';
import '../../../core/utils/app_text_styles.dart';
import '../../../core/widgets/custom_button.dart';
import '../../../core/widgets/custom_text_field.dart';
import '../controller/auth_controller.dart';

/// Modal Bottom Sheet for Two-Factor Challenge Verification
/// Conforms strictly to Phase 7 POST /auth/two-factor specs and AMS design system.
class TwoFactorSheet extends StatelessWidget {
  const TwoFactorSheet({super.key});

  static Future<void> show(BuildContext context) {
    return showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      backgroundColor: Colors.transparent,
      builder: (ctx) => Padding(
        padding: EdgeInsets.only(
          bottom: MediaQuery.of(ctx).viewInsets.bottom,
        ),
        child: const TwoFactorSheet(),
      ),
    );
  }

  @override
  Widget build(BuildContext context) {
    final controller = Get.find<AuthController>();

    return Container(
      decoration: BoxDecoration(
        color: AppColors.cardBackground,
        borderRadius: BorderRadius.only(
          topLeft: Radius.circular(20.r),
          topRight: Radius.circular(20.r),
        ),
        boxShadow: [
          BoxShadow(
            color: AppColors.primary.withValues(alpha: 0.15),
            blurRadius: 20.r,
            offset: Offset(0, -4.h),
          ),
        ],
      ),
      padding: EdgeInsets.symmetric(horizontal: 16.w, vertical: 20.h),
      child: Column(
        mainAxisSize: MainAxisSize.min,
        crossAxisAlignment: CrossAxisAlignment.stretch,
        children: [
          // Drag handle
          Center(
            child: Container(
              width: 40.w,
              height: 4.h,
              decoration: BoxDecoration(
                color: AppColors.borderColor,
                borderRadius: BorderRadius.circular(2.r),
              ),
            ),
          ),
          AppSpaces.vSpace16,

          // Icon and Title Header
          Row(
            children: [
              Container(
                width: 44.r,
                height: 44.r,
                decoration: BoxDecoration(
                  color: AppColors.secondary.withValues(alpha: 0.12),
                  borderRadius: BorderRadius.circular(12.r),
                ),
                child: Icon(
                  Icons.security_rounded,
                  color: AppColors.secondary,
                  size: 24.sp,
                ),
              ),
              AppSpaces.hSpace12,
              Expanded(
                child: Column(
                  crossAxisAlignment: CrossAxisAlignment.start,
                  children: [
                    Text(
                      'Two-Factor Verification',
                      style: AppTextStyles.text18.copyWith(
                        fontWeight: FontWeight.bold,
                        color: AppColors.textColor,
                      ),
                    ),
                    AppSpaces.vSpace2,
                    Text(
                      'Enter your security verification code',
                      style: AppTextStyles.text12.copyWith(
                        color: AppColors.hintColor,
                      ),
                    ),
                  ],
                ),
              ),
              IconButton(
                onPressed: () => Get.back(),
                icon: Icon(
                  Icons.close_rounded,
                  color: AppColors.hintColor,
                  size: 20.sp,
                ),
              ),
            ],
          ),
          AppSpaces.vSpace16,

          // Card Container with strict 12.w padding & 15.r border radius
          Container(
            decoration: BoxDecoration(
              color: AppColors.backgroundColor,
              borderRadius: BorderRadius.circular(15.r),
              border: Border.all(color: AppColors.borderColor, width: 1.w),
            ),
            padding: EdgeInsets.symmetric(horizontal: 12.w, vertical: 14.h),
            child: Obx(
              () => Column(
                crossAxisAlignment: CrossAxisAlignment.start,
                children: [
                  Text(
                    controller.isRecoveryCode.value
                        ? 'Enter single-use recovery backup code (e.g. A89F-22B1):'
                        : 'Enter the 6-digit TOTP code generated by your authenticator app:',
                    style: AppTextStyles.text12.copyWith(
                      color: AppColors.textColor,
                      fontWeight: FontWeight.w500,
                    ),
                  ),
                  AppSpaces.vSpace12,

                  // Code input field
                  CustomTextField(
                    labelText: controller.isRecoveryCode.value
                        ? 'Recovery Code'
                        : '6-Digit TOTP Code',
                    hintText: controller.isRecoveryCode.value
                        ? 'XXXX-XXXX'
                        : '000000',
                    controller: controller.twoFactorCodeController,
                    focusNode: controller.twoFactorFocusNode,
                    keyboardType: controller.isRecoveryCode.value
                        ? TextInputType.text
                        : TextInputType.number,
                    inputFormatters: controller.isRecoveryCode.value
                        ? [
                            FilteringTextInputFormatter.allow(
                              RegExp(r'[a-zA-Z0-9\-]'),
                            ),
                            LengthLimitingTextInputFormatter(16),
                          ]
                        : [
                            FilteringTextInputFormatter.digitsOnly,
                            LengthLimitingTextInputFormatter(6),
                          ],
                    prefixIcon: Icon(
                      controller.isRecoveryCode.value
                          ? Icons.key_rounded
                          : Icons.pin_rounded,
                      color: AppColors.hintColor,
                      size: 20.sp,
                    ),
                    onFieldSubmitted: (_) => controller.verifyTwoFactor(),
                  ),

                  // Inline Validation / Error Message
                  if (controller.twoFactorError.value != null &&
                      controller.twoFactorError.value!.isNotEmpty) ...[
                    AppSpaces.vSpace8,
                    Row(
                      children: [
                        Icon(
                          Icons.error_outline_rounded,
                          color: AppColors.error,
                          size: 16.sp,
                        ),
                        AppSpaces.hSpace6,
                        Expanded(
                          child: Text(
                            controller.twoFactorError.value!,
                            style: AppTextStyles.text12.copyWith(
                              color: AppColors.error,
                              fontWeight: FontWeight.w500,
                            ),
                          ),
                        ),
                      ],
                    ),
                  ],

                  AppSpaces.vSpace8,

                  // Toggle between TOTP and Recovery Code
                  Align(
                    alignment: Alignment.centerRight,
                    child: TextButton(
                      onPressed: () {
                        controller.isRecoveryCode.value =
                            !controller.isRecoveryCode.value;
                        controller.twoFactorCodeController.clear();
                        controller.twoFactorError.value = null;
                      },
                      style: TextButton.styleFrom(
                        padding: EdgeInsets.symmetric(
                          horizontal: 4.w,
                          vertical: 2.h,
                        ),
                        minimumSize: Size.zero,
                        tapTargetSize: MaterialTapTargetSize.shrinkWrap,
                      ),
                      child: Text(
                        controller.isRecoveryCode.value
                            ? 'Use Authenticator App TOTP code'
                            : 'Lost access? Use Recovery Code',
                        style: AppTextStyles.text12.copyWith(
                          color: AppColors.secondary,
                          fontWeight: FontWeight.w600,
                        ),
                      ),
                    ),
                  ),
                ],
              ),
            ),
          ),
          AppSpaces.vSpace16,

          // Verify Button (Pill shaped gradient)
          Obx(
            () => CustomButton(
              isGradient: true,
              text: 'Verify & Sign In',
              isLoading: controller.is2faLoading.value,
              onPressed: () => controller.verifyTwoFactor(),
            ),
          ),
          AppSpaces.vSpace10,

          // Notice
          Center(
            child: Text(
              'Security challenge is valid for 5 minutes',
              style: AppTextStyles.text10.copyWith(
                color: AppColors.hintColor,
              ),
            ),
          ),
        ],
      ),
    );
  }
}
